def build_dist(nodes: Dict[int, Node], round_int: bool = True) -> Dict[int, Dict[int, float]]:
    """ระยะแบบ EUC_2D มาตรฐาน VRPLIB — ต้องปัดเป็นจำนวนเต็มถึงจะเทียบ gap กับ optimal ทางการได้"""
    ids = list(nodes)
    D: Dict[int, Dict[int, float]] = {i: {} for i in ids}
    for i in ids:
        xi, yi = nodes[i]["x"], nodes[i]["y"]
        for j in ids:
            d = math.hypot(xi - nodes[j]["x"], yi - nodes[j]["y"])
            D[i][j] = float(round(d)) if round_int else d
    return D


def route_distance(route: List[int], D, depot: int) -> float:
    if not route:
        return 0.0
    d, prev = 0.0, depot
    for c in route:
        d += D[prev][c]
        prev = c
    return d + D[prev][depot]


def total_distance(routes: Routes, D, depot: int) -> float:
    return sum(route_distance(r, D, depot) for r in routes)


def route_load(route: List[int], nodes: Dict[int, Node]) -> float:
    return sum(nodes[c]["demand"] for c in route)


def copy_routes(routes: Routes) -> Routes:
    return [r[:] for r in routes]


