def randomized_nn(nodes, capacity, D, depot, rcl, rng: random.Random) -> Routes:
    """เพื่อนบ้านใกล้สุดแบบสุ่มจาก k ตัวที่ใกล้ที่สุด (Restricted Candidate List)"""
    unvisited = {i for i in nodes if i != depot}
    routes: Routes = []
    while unvisited:
        route: List[int] = []
        load, current, first = 0.0, depot, True
        while True:
            feas = [(D[current][i], i) for i in unvisited
                    if load + nodes[i]["demand"] <= capacity]
            if not feas:
                break
            if first:
                pick = rng.choice(feas)[1]                 # จุดเริ่มของคันนี้สุ่มเต็มที่
            else:
                feas.sort()
                pick = feas[rng.randrange(min(rcl, len(feas)))][1]
            route.append(pick)
            load += nodes[pick]["demand"]
            unvisited.discard(pick)
            current, first = pick, False
        if not route:
            break
        routes.append(route)
    return routes


def random_sweep(nodes, capacity, D, depot, rng: random.Random) -> Routes:
    """กวาดตามมุมรอบ depot โดยสุ่มมุมตั้งต้นและทิศหมุน"""
    ids = [i for i in nodes if i != depot]
    dx, dy = nodes[depot]["x"], nodes[depot]["y"]
    start = rng.random() * 2 * math.pi
    direction = 1 if rng.random() < 0.5 else -1
    scored = []
    for i in ids:
        a = math.atan2(nodes[i]["y"] - dy, nodes[i]["x"] - dx)
        a = (direction * (a - start)) % (2 * math.pi)
        scored.append((a, i))
    scored.sort()
    routes: Routes = []
    route: List[int] = []
    load = 0.0
    for _, i in scored:
        if load + nodes[i]["demand"] > capacity and route:
            routes.append(route); route, load = [], 0.0
        route.append(i); load += nodes[i]["demand"]
    if route:
        routes.append(route)
    return [two_opt(r, D, depot) for r in routes]


def clarke_wright(nodes, capacity, D, depot, noise, rng: random.Random) -> Routes:
    """Savings algorithm; noise > 0 ทำให้ลำดับการรวมเส้นทางต่างกันทุก restart"""
    ids = [i for i in nodes if i != depot]
    routes = [{"ids": [i], "load": nodes[i]["demand"]} for i in ids]
    savings = []
    for a_idx in range(len(ids)):
        for b_idx in range(a_idx + 1, len(ids)):
            a, b = ids[a_idx], ids[b_idx]
            s = D[depot][a] + D[depot][b] - D[a][b]
            if noise > 0:
                s *= 1 + (rng.random() * 2 - 1) * noise
            savings.append((s, a, b))
    savings.sort(key=lambda t: t[0], reverse=True)

    def find(node_id):
        for r in routes:
            if r["ids"][0] == node_id or r["ids"][-1] == node_id:
                return r
        return None

    for _, a, b in savings:
        ra, rb = find(a), find(b)
        if ra is None or rb is None or ra is rb:
            continue
        if ra["load"] + rb["load"] > capacity:
            continue
        a_end, a_start = ra["ids"][-1] == a, ra["ids"][0] == a
        b_end, b_start = rb["ids"][-1] == b, rb["ids"][0] == b
        if a_end and b_start:
            merged = ra["ids"] + rb["ids"]
        elif b_end and a_start:
            merged = rb["ids"] + ra["ids"]
        elif a_end and b_end:
            merged = ra["ids"] + rb["ids"][::-1]
        elif a_start and b_start:
            merged = ra["ids"][::-1] + rb["ids"]
        else:
            continue
        load = ra["load"] + rb["load"]
        routes = [r for r in routes if r is not ra and r is not rb]
        routes.append({"ids": merged, "load": load})
    return [r["ids"] for r in routes]


# ================================================================ local search
def two_opt(route: List[int], D, depot: int) -> List[int]:
    """สแกน i<j แล้วกลับด้านท่อน แต่คิดส่วนต่างแบบ O(1) แทนการคำนวณระยะทั้งเส้นใหม่"""
    best = route[:]
    improved = True
    while improved:
        improved = False
        for i in range(len(best) - 1):
            for j in range(i + 1, len(best)):
                prev = best[i - 1] if i > 0 else depot
                nxt = best[j + 1] if j < len(best) - 1 else depot
                a, b = best[i], best[j]
                delta = D[prev][b] + D[a][nxt] - D[prev][a] - D[b][nxt]
                if delta < -1e-9:
                    best[i:j + 1] = best[i:j + 1][::-1]
                    improved = True
    return best


def or_opt_pass(routes, nodes, D, capacity, depot):
    """ย้ายท่อนยาว 1-3 จุด (สลับทิศได้) ไปตำแหน่งอื่น — เจอดีขึ้นแล้วคืนทันที"""
    for ri in range(len(routes)):
        for seg_len in (1, 2, 3):
            for i in range(len(routes[ri]) - seg_len + 1):
                segment = routes[ri][i:i + seg_len]
                remainder = routes[ri][:i] + routes[ri][i + seg_len:]
                seg_load = route_load(segment, nodes)
                variants = [segment, segment[::-1]] if seg_len > 1 else [segment]
                for rj in range(len(routes)):
                    base = remainder if rj == ri else routes[rj]
                    if route_load(base, nodes) + seg_load > capacity:
                        continue
                    old = route_distance(routes[ri], D, depot)
                    if rj != ri:
                        old += route_distance(routes[rj], D, depot)
                    for pos in range(len(base) + 1):
                        if rj == ri and i <= pos <= i + seg_len:
                            continue
                        for seg in variants:
                            new_target = base[:pos] + seg + base[pos:]
                            if rj == ri:
                                new = route_distance(new_target, D, depot)
                            else:
                                new = (route_distance(remainder, D, depot)
                                       + route_distance(new_target, D, depot))
                            if new < old - 1e-9:
                                out = copy_routes(routes)
                                if rj == ri:
                                    out[ri] = new_target
                                else:
                                    out[ri], out[rj] = remainder, new_target
                                return True, [r for r in out if r]
    return False, routes


def swap_pass(routes, nodes, D, capacity, depot):
    for ri in range(len(routes)):
        for ci in range(len(routes[ri])):
            for rj in range(ri, len(routes)):
                start_cj = ci + 1 if rj == ri else 0
                for cj in range(start_cj, len(routes[rj])):
                    ci_cust, cj_cust = routes[ri][ci], routes[rj][cj]
                    new_ri = routes[ri][:]
                    new_rj = new_ri if ri == rj else routes[rj][:]
                    new_ri[ci] = cj_cust
                    if ri == rj:
                        new_ri[cj] = ci_cust
                    else:
                        new_rj[cj] = ci_cust
                    if route_load(new_ri, nodes) > capacity:
                        continue
                    if ri != rj and route_load(new_rj, nodes) > capacity:
                        continue
                    old = route_distance(routes[ri], D, depot)
                    new = route_distance(new_ri, D, depot)
                    if ri != rj:
                        old += route_distance(routes[rj], D, depot)
                        new += route_distance(new_rj, D, depot)
                    if new < old - 1e-9:
                        out = copy_routes(routes)
                        out[ri] = new_ri
                        if ri != rj:
                            out[rj] = new_rj
                        return True, out
    return False, routes


def local_search(routes: Routes, nodes, D, capacity, depot, max_iter: int = 200) -> Routes:
    routes = copy_routes(routes)
    for _ in range(max_iter):
        improved = False
        for ri in range(len(routes)):
            nr = two_opt(routes[ri], D, depot)
            if route_distance(nr, D, depot) < route_distance(routes[ri], D, depot) - 1e-9:
                routes[ri], improved = nr, True
        ok, routes = or_opt_pass(routes, nodes, D, capacity, depot)
        if ok:
            continue
        ok2, routes = swap_pass(routes, nodes, D, capacity, depot)
        improved = improved or ok2
        if not improved:
            break
    return [r for r in routes if r]


# ================================================================ destroy / repair
def random_removal(routes, q, nodes, D, depot, rng: random.Random):
    routes = copy_routes(routes)
    allc = [c for r in routes for c in r]
    rng.shuffle(allc)
    removed = allc[:min(q, len(allc))]
    rs = set(removed)
    return [[c for c in r if c not in rs] for r in routes], removed


def worst_removal(routes, q, nodes, D, depot, rng: random.Random, p: int = 3):
    routes = copy_routes(routes)
    removed = []
    for _ in range(q):
        cands = []
        for ri, r in enumerate(routes):
            for ci, c in enumerate(r):
                prev = r[ci - 1] if ci > 0 else depot
                nxt = r[ci + 1] if ci < len(r) - 1 else depot
                cands.append((D[prev][c] + D[c][nxt] - D[prev][nxt], ri, ci, c))
        if not cands:
            break
        cands.sort(reverse=True)
        idx = min(len(cands) - 1, int((rng.random() ** p) * len(cands)))
        _, ri, ci, c = cands[idx]
        routes[ri].pop(ci)
        removed.append(c)
    return routes, removed


def related_removal(routes, q, nodes, D, depot, rng: random.Random, p: int = 3):
    """Shaw removal — เอาลูกค้าที่อยู่ใกล้กันออกพร้อมกัน เพื่อให้ซ่อมแล้วเปลี่ยนโครงสร้างจริง"""
    routes = copy_routes(routes)
    allc = [c for r in routes for c in r]
    if not allc:
        return routes, []

    def drop(cust):
        for r in routes:
            if cust in r:
                r.remove(cust)
                return

    seed = rng.choice(allc)
    drop(seed)
    removed = [seed]
    while len(removed) < q:
        remaining = [c for r in routes for c in r]
        if not remaining:
            break
        ref = rng.choice(removed)
        remaining.sort(key=lambda c: D[ref][c])
        idx = min(len(remaining) - 1, int((rng.random() ** p) * len(remaining)))
        chosen = remaining[idx]
        drop(chosen)
        removed.append(chosen)
    return routes, removed


def best_insertion(route, cust, nodes, D, capacity, depot):
    if route_load(route, nodes) + nodes[cust]["demand"] > capacity:
        return None
    best = None
    for pos in range(len(route) + 1):
        prev = route[pos - 1] if pos > 0 else depot
        nxt = route[pos] if pos < len(route) else depot
        cost = D[prev][cust] + D[cust][nxt] - D[prev][nxt]
        if best is None or cost < best[1]:
            best = (pos, cost)
    return best


def greedy_insertion(routes, removed, nodes, D, capacity, depot, rng: random.Random):
    routes = copy_routes(routes)
    todo = removed[:]
    while todo:
        best = None  # (cost, cust_idx, route_idx, pos, new_route)
        for ci, cust in enumerate(todo):
            for ri, r in enumerate(routes):
                bi = best_insertion(r, cust, nodes, D, capacity, depot)
                if bi and (best is None or bi[1] < best[0]):
                    best = (bi[1], ci, ri, bi[0], False)
            nc = D[depot][cust] * 2
            if nodes[cust]["demand"] <= capacity and (best is None or nc < best[0]):
                best = (nc, ci, -1, 0, True)
        if best is None:
            routes.append([todo.pop(0)])
            continue
        _, ci, ri, pos, new_route = best
        cust = todo.pop(ci)
        if new_route:
            routes.append([cust])
        else:
            routes[ri].insert(pos, cust)
    return [r for r in routes if r]


def regret_insertion(routes, removed, nodes, D, capacity, depot, rng: random.Random):
    routes = copy_routes(routes)
    todo = removed[:]
    while todo:
        best_cust_idx, best_regret, best_choice = -1, -float("inf"), None
        for ci, cust in enumerate(todo):
            options = []
            for ri, r in enumerate(routes):
                bi = best_insertion(r, cust, nodes, D, capacity, depot)
                if bi:
                    options.append((bi[1], ri, bi[0], False))
            if nodes[cust]["demand"] <= capacity:
                options.append((D[depot][cust] * 2, -1, 0, True))
            if not options:
                continue
            options.sort()
            second = options[1][0] if len(options) > 1 else options[0][0] + 1e6
            regret = second - options[0][0]
            if regret > best_regret:
                best_regret, best_cust_idx, best_choice = regret, ci, options[0]
        if best_choice is None:
            routes.append([todo.pop(0)])
            continue
        cust = todo.pop(best_cust_idx)
        _, ri, pos, new_route = best_choice
        if new_route:
            routes.append([cust])
        else:
            routes[ri].insert(pos, cust)
    return [r for r in routes if r]


# ================================================================ จำนวนรถ + การบังคับ K
def enforce_vehicle_limit(routes: Routes, nodes, D, capacity, depot,
                           max_vehicles: Optional[int]) -> Routes:
    """ถ้าจำนวนคันเกิน K ให้รวมคู่เส้นทางที่ทำให้ระยะทางเพิ่มขึ้นน้อยที่สุดไปเรื่อย ๆ จนเหลือ <= K"""
    out = [r[:] for r in routes if r]
    if not max_vehicles:
        return out
    while len(out) > max_vehicles:
        best = None  # (increase, i, j, merged)
        for i in range(len(out)):
            for j in range(i + 1, len(out)):
                a, b = out[i], out[j]
                if route_load(a, nodes) + route_load(b, nodes) > capacity + 1e-9:
                    continue
                before = route_distance(a, D, depot) + route_distance(b, D, depot)
                for merged in (a + b, b + a):
                    after = route_distance(merged, D, depot)
                    increase = after - before
                    if best is None or increase < best[0]:
                        best = (increase, i, j, merged)
        if best is None:                       # ไม่มีคู่ไหนรวมกันได้แบบไม่เกิน capacity
            break
        _, i, j, merged = best
        out = [r for idx, r in enumerate(out) if idx != i and idx != j]
        out.append(merged)
    return out


# ================================================================ เฟส 2: ALNS
def alns(initial: Routes, nodes, D, capacity, depot, cfg: dict, rng: random.Random,
         init_dw=None, init_rw=None, max_vehicles: Optional[int] = None,
         on_progress=None) -> dict:
    iterations = cfg["iterations"]
    segment = cfg["segment"]
    decay = cfg["decay"]
    dmin, dmax = cfg["destroy_min"], cfg["destroy_max"]

    current = copy_routes(initial)
    current_cost = total_distance(current, D, depot)
    best, best_cost = copy_routes(current), current_cost

    destroy_ops = [random_removal, worst_removal, related_removal]
    repair_ops = [greedy_insertion, regret_insertion]
    dw = list(init_dw) if init_dw else [1.0, 1.0, 1.0]
    rw = list(init_rw) if init_rw else [1.0, 1.0]
    d_score, r_score = [0.0] * 3, [0.0] * 2
    d_use, r_use = [0] * 3, [0] * 2

    cust_count = len(nodes) - 1
    T = max(current_cost * 0.05, 1e-6)
    cooling = 0.9995

    def roulette(weights):
        total = sum(weights)
        x = rng.random() * total
        for i, w in enumerate(weights):
            x -= w
            if x <= 0:
                return i
        return len(weights) - 1

    for it in range(iterations):
        di, ri_ = roulette(dw), roulette(rw)
        d_use[di] += 1
        r_use[ri_] += 1
        q = max(1, int(cust_count * (dmin + rng.random() * (dmax - dmin))))
        destroyed, removed = destroy_ops[di](current, q, nodes, D, depot, rng)
        if not removed:
            continue
        repaired = repair_ops[ri_](destroyed, removed, nodes, D, capacity, depot, rng)
        repaired = enforce_vehicle_limit(repaired, nodes, D, capacity, depot, max_vehicles)
        new_cost = total_distance(repaired, D, depot)

        gain = 0
        if new_cost < best_cost - 1e-9:
            best, best_cost = copy_routes(repaired), new_cost
            current, current_cost, gain = repaired, new_cost, 33
        elif new_cost < current_cost - 1e-9:
            current, current_cost, gain = repaired, new_cost, 13
        else:
            delta = new_cost - current_cost
            if rng.random() < math.exp(-delta / T):
                current, current_cost, gain = repaired, new_cost, 6
        d_score[di] += gain
        r_score[ri_] += gain
        T = max(T * cooling, 1e-6)

        if (it + 1) % segment == 0:
            for i in range(len(dw)):
                if d_use[i]:
                    dw[i] = dw[i] * decay + (1 - decay) * (d_score[i] / d_use[i])
                d_score[i], d_use[i] = 0.0, 0
            for i in range(len(rw)):
                if r_use[i]:
                    rw[i] = rw[i] * decay + (1 - decay) * (r_score[i] / r_use[i])
                r_score[i], r_use[i] = 0.0, 0
            current = local_search(current, nodes, D, capacity, depot, 20)
            current_cost = total_distance(current, D, depot)
            if current_cost < best_cost - 1e-9:
                best, best_cost = copy_routes(current), current_cost
            if on_progress:
                on_progress(it + 1, iterations, best_cost)

    best = local_search(best, nodes, D, capacity, depot, 100)
    best = enforce_vehicle_limit(best, nodes, D, capacity, depot, max_vehicles)
    return {"routes": best, "cost": total_distance(best, D, depot), "dw": dw, "rw": rw}


# ================================================================ เฟส 1: Random Multi-Restart
def signature(routes: Routes) -> str:
    return "|".join(sorted("-".join(map(str, sorted(r))) for r in routes))


def random_multi_restart(nodes, capacity, D, depot, cfg: dict, rng: random.Random,
                          max_vehicles: Optional[int] = None, log=print):
    pool: List[dict] = []
    seen = set()
    costs = []
    method_stats: Dict[str, dict] = {}

    for r in range(cfg["restarts"]):
        u = rng.random()
        if u < 0.5:
            routes, method = randomized_nn(nodes, capacity, D, depot, cfg["rcl"], rng), "Randomized NN"
        elif u < 0.8:
            routes, method = clarke_wright(nodes, capacity, D, depot, cfg["cw_noise"], rng), "Clarke-Wright + noise"
        else:
            routes, method = random_sweep(nodes, capacity, D, depot, rng), "Random Sweep"

        routes = local_search(routes, nodes, D, capacity, depot, cfg["quick_ls"])
        routes = enforce_vehicle_limit(routes, nodes, D, capacity, depot, max_vehicles)
        cost = total_distance(routes, D, depot)
        costs.append(cost)

        st = method_stats.setdefault(method, {"n": 0, "sum": 0.0, "best": float("inf")})
        st["n"] += 1
        st["sum"] += cost
        st["best"] = min(st["best"], cost)

        sig = signature(routes)
        if sig not in seen:                 # เก็บเฉพาะโครงสร้างที่ไม่ซ้ำ รักษาความหลากหลาย
            seen.add(sig)
            pool.append({"routes": routes, "cost": cost, "method": method, "restart": r + 1})
            pool.sort(key=lambda e: e["cost"])
            del pool[cfg["elites"]:]

        if log and ((r + 1) % 10 == 0 or r + 1 == cfg["restarts"]):
            log(f"  restart {r + 1}/{cfg['restarts']} — ดีที่สุดตอนนี้ {pool[0]['cost']:.2f}")

    mean = sum(costs) / len(costs)
    std = math.sqrt(sum((c - mean) ** 2 for c in costs) / len(costs))
    stats = {"count": len(costs), "best": min(costs), "worst": max(costs), "mean": mean, "std": std}
    return pool, stats, method_stats


# ================================================================ ตรวจคำตอบ
def validate(routes: Routes, nodes, capacity, depot, max_vehicles: Optional[int] = None) -> List[str]:
    problems = []
    seen: Dict[int, int] = {}
    for idx, r in enumerate(routes, 1):
        load = route_load(r, nodes)
        if load > capacity + 1e-9:
            problems.append(f"คัน {idx} โหลด {load:.0f} > capacity {capacity}")
        for c in r:
            seen[c] = seen.get(c, 0) + 1
    customers = {i for i in nodes if i != depot}
    missing = sorted(customers - set(seen))
    dup = sorted(c for c, n in seen.items() if n > 1)
    if missing:
        problems.append(f"ลูกค้าตกหล่น: {missing}")
    if dup:
        problems.append(f"ลูกค้าซ้ำ: {dup}")
    if max_vehicles and len(routes) > max_vehicles:
        problems.append(f"จำนวนรถ {len(routes)} > K={max_vehicles}")
    return problems


# ================================================================ Held-Karp — exact TSP ต่อเส้นทาง
def held_karp_route(route: List[int], D, depot: int) -> List[int]:
    """หาลำดับที่ดีที่สุดจริงของเส้นทางเดียวด้วย DP บนเซตย่อย O(2^m * m^2)"""
    m = len(route)
    if m <= 2:
        return route[:]
    full = (1 << m) - 1
    INF = float("inf")
    dp = [[INF] * m for _ in range(full + 1)]
    par = [[-1] * m for _ in range(full + 1)]
    for j in range(m):
        dp[1 << j][j] = D[depot][route[j]]
    for mask in range(1, full + 1):
        row = dp[mask]
        for j in range(m):
            cur = row[j]
            if cur == INF or not (mask & (1 << j)):
                continue
            for k in range(m):
                if mask & (1 << k):
                    continue
                nm = mask | (1 << k)
                val = cur + D[route[j]][route[k]]
                if val < dp[nm][k] - 1e-12:
                    dp[nm][k] = val
                    par[nm][k] = j
    best_end, best_val = -1, INF
    for j in range(m):
        v = dp[full][j] + D[route[j]][depot]
        if v < best_val - 1e-12:
            best_val, best_end = v, j
    order, mask, j = [], full, best_end
    while j != -1:
        order.append(route[j])
        pj = par[mask][j]
        mask ^= (1 << j)
        j = pj
    order.reverse()
    return order


def exact_validate(routes: Routes, D, depot: int, max_size: int = 12, log=print):
    """ยืนยันด้วย Held-Karp ว่าลำดับภายในเส้นทางที่เล็กพอเป็น optimal แล้ว (และแก้ให้ถ้ายัง)"""
    out = copy_routes(routes)
    checked = skipped = improved = 0
    gained = 0.0
    for i, r in enumerate(out):
        if len(r) > max_size:
            skipped += 1
            continue
        checked += 1
        before = route_distance(r, D, depot)
        opt = held_karp_route(r, D, depot)
        after = route_distance(opt, D, depot)
        if after < before - 1e-9:
            improved += 1
            gained += before - after
            out[i] = opt
            if log:
                log(f"    คัน {i + 1}: ลำดับยังไม่ optimal — {before:.2f} → {after:.2f} (แก้ให้แล้ว)")
    return out, {"checked": checked, "skipped": skipped, "improved": improved, "gained": gained}


# ================================================================ ตัวขับสองเฟส (run_hybrid)
def run_hybrid(nodes, capacity, D, depot, args, rng: random.Random,
               max_vehicles: Optional[int] = None, log=print) -> dict:
    t0 = time.perf_counter()
    if log:
        log("\n[เฟส 1] Random Multi-Restart — สำรวจพื้นที่คำตอบ")
    pool, stats, method_stats = random_multi_restart(
        nodes, capacity, D, depot,
        {"restarts": args.restarts, "elites": args.elites, "rcl": args.rcl,
         "cw_noise": args.cw_noise, "quick_ls": args.quick_ls},
        rng, max_vehicles, log)
    t1 = time.perf_counter()

    if log:
        log(f"  restart ทั้งหมด {stats['count']} ครั้ง | "
            f"ดีที่สุด {stats['best']:.2f} | เฉลี่ย {stats['mean']:.2f} | "
            f"แย่ที่สุด {stats['worst']:.2f} | s.d. {stats['std']:.2f}")
        for m, v in method_stats.items():
            log(f"    - {m:<24} ใช้ {v['n']:>3} ครั้ง | ดีที่สุด {v['best']:.2f} | เฉลี่ย {v['sum'] / v['n']:.2f}")
        log(f"  ⏱️ {t1 - t0:.2f} วินาที — คัด elite {len(pool)} ตัว")
        log("\n[เฟส 2] ALNS — เจาะลึก elite แต่ละตัว")

    weights = [1 / (i + 1) for i in range(len(pool))]       # elite อันดับ 1 ได้งบมากสุด
    wsum = sum(weights)
    budgets = [max(args.segment, int(args.iters * w / wsum)) for w in weights]

    dw, rw = None, None
    best_routes, best_cost, best_from = None, float("inf"), None
    for i, elite in enumerate(pool):
        cfg = {"iterations": budgets[i], "segment": args.segment, "decay": args.decay,
               "destroy_min": args.destroy_min, "destroy_max": args.destroy_max}
        res = alns(elite["routes"], nodes, D, capacity, depot, cfg, rng,
                   init_dw=dw, init_rw=rw, max_vehicles=max_vehicles)
        if not args.no_carry_weights:
            dw, rw = res["dw"], res["rw"]
        if log:
            imp = elite["cost"] - res["cost"]
            log(f"  elite {i + 1} ({elite['method']}, restart #{elite['restart']}): "
                f"{elite['cost']:.2f} → {res['cost']:.2f} "
                f"(-{imp:.2f}, {imp / elite['cost'] * 100:.2f}%) ด้วย {budgets[i]} iter")
        if res["cost"] < best_cost:
            best_cost, best_routes, best_from = res["cost"], res["routes"], i + 1
    t2 = time.perf_counter()
    if log:
        log(f"  ⏱️ {t2 - t1:.2f} วินาที")
    return {"routes": best_routes, "cost": best_cost, "from_elite": best_from,
            "stats": stats, "seconds": t2 - t0}


