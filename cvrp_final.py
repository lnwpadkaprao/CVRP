# ================================================================ อ่านไฟล์ .vrp (VRPLIB format)
def parse_vrp(path: str) -> Tuple[Dict[int, Node], int, float, str, int]:
    """คืนค่า (nodes, capacity, optimal, edge_type, depot)"""
    coords: Dict[int, Tuple[float, float]] = {}
    demands: Dict[int, float] = {}
    capacity: Optional[int] = None
    optimal = 0.0
    section = ""
    edge_type = ""
    depot_ids: List[int] = []

    with open(path, encoding="utf-8", errors="ignore") as fh:
        for raw in fh:
            line = raw.strip()
            if not line:
                continue
            upper = line.upper()
            if "EDGE_WEIGHT_TYPE" in upper and ":" in line:
                edge_type = line.split(":")[1].strip().upper()
                continue
            if "CAPACITY" in upper and ":" in line:
                capacity = int(float(line.split(":")[1].strip()))
                continue
            if "COMMENT" in upper:
                low = line.lower()
                if "optimal value" in low:
                    digits = "".join(
                        c if c.isdigit() or c == "." else " "
                        for c in low.split("optimal value")[1]
                    )
                    parts = digits.split()
                    if parts:
                        optimal = float(parts[0])
                continue
            if upper.startswith("NODE_COORD_SECTION"):
                section = "COORD"; continue
            if upper.startswith("DEMAND_SECTION"):
                section = "DEMAND"; continue
            if upper.startswith("DEPOT_SECTION"):
                section = "DEPOT"; continue
            if upper.startswith("EOF"):
                section = ""; continue

            parts = line.split()
            try:
                nums = [float(p) for p in parts]
            except ValueError:
                continue
            if section == "COORD" and len(nums) >= 3:
                coords[int(nums[0])] = (nums[1], nums[2])
            elif section == "DEMAND" and len(nums) >= 2:
                demands[int(nums[0])] = nums[1]
            elif section == "DEPOT" and nums and nums[0] > 0:
                depot_ids.append(int(nums[0]))

    if capacity is None:
        raise ValueError("ไม่พบ CAPACITY ในไฟล์")
    if not coords:
        raise ValueError(
            "ไม่พบ NODE_COORD_SECTION — รองรับเฉพาะ instance ที่ให้พิกัด (EUC_2D), "
            "ไม่รองรับ EDGE_WEIGHT_SECTION แบบเมทริกซ์"
        )
    if edge_type and edge_type != "EUC_2D":
        raise ValueError(f"EDGE_WEIGHT_TYPE = {edge_type} ยังไม่รองรับ (รองรับเฉพาะ EUC_2D)")

    nodes = {i: {"x": xy[0], "y": xy[1], "demand": demands.get(i, 0.0)}
             for i, xy in coords.items()}
    depot = depot_ids[0] if depot_ids and depot_ids[0] in nodes else min(nodes)
    return nodes, capacity, optimal, edge_type or "(ไม่ระบุ — ถือเป็น EUC_2D)", depot


def infer_vehicle_limit(path: str) -> Optional[int]:
    """อ่านจำนวนรถสูงสุด K จากชื่อไฟล์รูปแบบ "-kN" เช่น A-n32-k5.vrp -> 5"""
    m = re.search(r"-k(\d+)", path, re.IGNORECASE)
    return int(m.group(1)) if m else None


